import { describe, expect, it } from 'vitest';
import {
  MessageBuilder,
  alertCard,
  approvalRequest,
  card,
  chartImage,
  compactTable,
  compose,
  createMessage,
  defineComponent,
  deploymentNotice,
  digest,
  fallbackFromBlocks,
  imageAlert,
  incidentUpdate,
  message,
  metricGrid,
  prebuilt,
  resolveComponent,
  resolveComponents,
  section,
  validateMessage
} from '../src';

describe('component framework', () => {
  it('defines and resolves custom components', () => {
    const customerComponent = defineComponent<{ name: string; score: number }>('customer.score', (props, { blocks }) => ({
      blocks: [
        blocks.header(`Customer ${props.name}`),
        blocks.section({ fields: [{ label: 'Score', value: props.score }] })
      ],
      fallbackText: `${props.name}: ${props.score}`
    }));

    const rendered = resolveComponent(customerComponent({ name: 'Acme', score: 98 }));
    expect(rendered.blocks).toHaveLength(2);
    expect(rendered.fallbackText).toBe('Acme: 98');

    const normalizedBlock = resolveComponent(section('inline block'));
    expect(normalizedBlock.blocks).toHaveLength(1);

    const normalizedArray = resolveComponent([section('a'), section('b')]);
    expect(normalizedArray.blocks).toHaveLength(2);

    const merged = resolveComponents([customerComponent({ name: 'Beta', score: 80 }), section('extra')]);
    expect(merged.blocks).toHaveLength(3);
    expect(merged.fallbackText).toBe('Beta: 80');
  });

  it('supports custom components returning another component', () => {
    const wrapper = defineComponent<{ title: string }>('wrapper', (props) => card({ title: props.title, body: 'wrapped', severity: 'success' }));
    const rendered = resolveComponent(wrapper({ title: 'Nested' }));
    expect(rendered.blocks[0]?.type).toBe('header');
    expect(rendered.fallbackText).toContain('Nested');
  });
});

describe('prebuilt components', () => {
  it('renders a card with body, fields, context, thumbnail, actions, and divider', () => {
    const rendered = resolveComponent(card({
      title: 'Daily report',
      body: ['All systems healthy', 'No incidents'],
      severity: 'success',
      thumbnailUrl: 'https://example.com/thumb.png',
      thumbnailAltText: 'thumb',
      fields: [
        { label: 'Errors', value: 0 },
        { label: 'SLO', value: '99.99%' }
      ],
      context: ['Generated by tests'],
      actions: [{ text: 'View', url: 'https://example.com/report' }],
      includeDivider: true
    }));

    expect(rendered.blocks.map((block) => block.type)).toEqual(['header', 'section', 'section', 'context', 'actions', 'divider']);
    expect(rendered.fallbackText).toContain('Daily report');
  });

  it('renders alert cards and adds runbook actions only when provided', () => {
    const withRunbook = resolveComponent(alertCard({
      title: 'Latency high',
      message: 'p95 exceeded threshold',
      severity: 'danger',
      source: 'datadog',
      timestamp: '2026-05-20T12:00:00Z',
      runbookUrl: 'https://example.com/runbook'
    }));
    const actionsBlock = withRunbook.blocks.find((block) => block.type === 'actions') as { elements: unknown[] } | undefined;
    expect(actionsBlock?.elements).toHaveLength(1);

    const withoutRunbook = resolveComponent(alertCard({ title: 'FYI', message: 'No action needed' }));
    expect(withoutRunbook.blocks.some((block) => block.type === 'actions')).toBe(false);
  });

  it('renders image and chart messages', () => {
    const imageMessage = resolveComponent(imageAlert({
      title: 'Security snapshot',
      message: 'New camera frame',
      imageUrl: 'https://example.com/frame.jpg',
      altText: 'A camera frame showing an empty hallway',
      caption: 'Frame generated at noon',
      actions: [{ text: 'Investigate', value: 'investigate' }]
    }));
    expect(imageMessage.blocks.map((block) => block.type)).toEqual(['header', 'section', 'image', 'context', 'actions']);

    const chartMessage = resolveComponent(chartImage({
      title: 'Revenue trend',
      chartUrl: 'https://example.com/chart.png',
      altText: 'Line chart trending up',
      summary: 'Revenue is up week over week.',
      metrics: [{ label: 'ARR', value: '$10M' }],
      actions: [{ text: 'Open dashboard', url: 'https://example.com/dashboard' }]
    }));
    expect(chartMessage.blocks.some((block) => block.type === 'image')).toBe(true);
  });

  it('renders metric grids, compact tables, and digests across edge branches', () => {
    const metrics = resolveComponent(metricGrid({
      title: 'Service health',
      metrics: [
        { label: 'Uptime', value: 99.99, unit: '%', delta: '+0.1', severity: 'success' },
        { label: 'Errors', value: 3, severity: 'warning' }
      ],
      context: ['Past 24h'],
      maxMetrics: 1
    }));
    expect(metrics.blocks.map((block) => block.type)).toEqual(['header', 'section', 'context']);

    const table = resolveComponent(compactTable({
      title: 'Top queues',
      columns: [
        { key: 'name', width: 8 },
        { key: 'depth', align: 'right', width: 5 }
      ],
      rows: [
        { name: 'alpha', depth: 10 },
        { name: 'bravo', depth: 20 },
        { name: 'charlie', depth: 30 }
      ],
      maxRows: 2
    }));
    expect(table.blocks).toHaveLength(3);
    expect(fallbackFromBlocks(table.blocks)).toContain('Top queues');

    const emptyTable = resolveComponent(compactTable({ title: 'Empty', columns: [{ key: 'name' }], rows: [], emptyText: 'Nothing here' }));
    expect(fallbackFromBlocks(emptyTable.blocks)).toContain('Nothing here');

    const feed = resolveComponent(digest({
      title: 'Release digest',
      items: [
        { title: 'API deployed', severity: 'success', url: 'https://example.com/1' },
        { title: 'Worker queued', text: 'Backlog growing', severity: 'warning' },
        { title: 'Long', text: 'x'.repeat(300) }
      ],
      maxItems: 2,
      actions: [{ text: 'View all', url: 'https://example.com/all' }]
    }));
    expect(feed.blocks.map((block) => block.type)).toEqual(['header', 'section', 'section', 'actions']);

    const emptyDigest = resolveComponent(digest({ title: 'Empty digest', items: [] }));
    expect(fallbackFromBlocks(emptyDigest.blocks)).toContain('No updates');
  });

  it('renders domain-specific prebuilt messages', () => {
    expect(resolveComponent(deploymentNotice({
      service: 'api',
      environment: 'prod',
      version: '1.2.3',
      status: 'failed',
      actor: 'U123',
      commit: 'abc123',
      url: 'https://example.com/deploy'
    })).blocks.some((block) => block.type === 'actions')).toBe(true);

    expect(resolveComponent(incidentUpdate({
      incidentId: 'INC-123',
      title: 'Checkout degraded',
      status: 'Investigating',
      summary: 'Payments are intermittently failing.',
      impact: 'Some customers cannot check out.',
      owner: 'payments',
      startedAt: '12:00',
      nextUpdateAt: '12:30',
      actions: [{ text: 'Status page', url: 'https://status.example.com' }]
    })).blocks.length).toBeGreaterThan(2);

    const approval = resolveComponent(approvalRequest({
      title: 'Approve deploy',
      requester: 'alice',
      reason: 'Deploying hotfix',
      approveUrl: 'https://example.com/approve',
      rejectUrl: 'https://example.com/reject',
      fields: [{ label: 'Risk', value: 'low' }]
    }));
    const actionBlock = approval.blocks.find((block) => block.type === 'actions') as { elements: Array<{ style?: string }> } | undefined;
    expect(actionBlock?.elements.map((element) => element.style)).toEqual(['primary', 'danger']);
  });

  it('exports prebuilt namespace helpers', () => {
    expect(resolveComponent(prebuilt.card({ title: 'Namespace', body: 'ok' })).blocks[0]?.type).toBe('header');
  });
});

describe('message builder', () => {
  it('composes prebuilt and primitive content into a message payload', () => {
    const payload = message({ unfurlLinks: false })
      .header('Ops summary')
      .section('Generated automatically')
      .divider()
      .alert({ title: 'Cache warm', message: 'Cache is ready', severity: 'success' })
      .metrics({ title: 'KPI', metrics: [{ label: 'Latency', value: 120, unit: 'ms' }] })
      .table({ title: 'Jobs', columns: [{ key: 'name' }, { key: 'status' }], rows: [{ name: 'sync', status: 'done' }] })
      .digest({ title: 'Updates', items: [{ title: 'Done' }] })
      .deployment({ service: 'worker', environment: 'staging', version: '2.0.0', status: 'started' })
      .incident({ incidentId: 'INC-1', title: 'Minor issue', status: 'Monitoring', summary: 'Stable', severity: 'warning' })
      .approval({ title: 'Approve access', requester: 'bob', reason: 'Needs temporary access' })
      .build({ text: 'Ops summary fallback', metadata: { event_type: 'ops_summary', event_payload: { id: '1' } }, mrkdwn: false, parse: 'none' });

    expect(payload.text).toBe('Ops summary fallback');
    expect(payload.unfurl_links).toBe(false);
    expect(payload.metadata?.event_type).toBe('ops_summary');
    expect(validateMessage(payload).filter((issue) => issue.severity === 'error')).toHaveLength(0);
  });

  it('supports static construction and createMessage helper', () => {
    const fromStatic = MessageBuilder.create({ text: 'default' }).card({ title: 'Card only' }).build();
    expect(fromStatic.text).toBe('default');

    const composed = compose().add(card({ title: 'One' })).addMany([section('Two')]).build({ unfurlMedia: false });
    expect(composed.unfurl_media).toBe(false);

    const direct = createMessage([card({ title: 'Direct', body: 'Body' })]);
    expect(direct.text).toContain('Direct');
  });

  it('can build without validation for intentionally custom payloads', () => {
    const payload = new MessageBuilder({ validate: false }).add({ type: 'section' }).build({ text: 'invalid but intentionally skipped' });
    expect(payload.blocks).toHaveLength(1);
  });
});
