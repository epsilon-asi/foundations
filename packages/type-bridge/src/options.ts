import type { PropertyCase } from './shared/naming.js';
import type { QuoteStyle } from './shared/strings.js';

/**
 * Replaces a source type with target-language text.
 *
 * Keys are matched against the name as written (`ObjectId`) and its qualified form (`bson.ObjectId`,
 * `datetime.datetime`). A value is the target type text, or that plus the import lines it needs.
 */
export type TypeMap = Record<string, string | { type: string; imports?: string[] }>;

/** Options both directions share. */
export interface CommonOptions {
  /** Source-to-target type overrides. Default: none. */
  typeMap?: TypeMap;
  /** How property names are rewritten. Default: `'preserve'`. */
  propertyCase?: PropertyCase;
  /** A comment placed at the top of the output, or `false` for none. Default: {@link DEFAULT_HEADER}. */
  header?: string | false;
  /** Throw a `ConversionError` instead of returning when any warning was recorded. Default: false. */
  strict?: boolean;
  /** Members whose names start with `_` (and are not pydantic/dataclass fields). Default: false. */
  includePrivate?: boolean;
}

export const DEFAULT_HEADER = 'Generated by @epsilon-asi/type-bridge.';

// ---------------------------------------------------------------------------
// Python → TypeScript
// ---------------------------------------------------------------------------

/**
 * What the TypeScript types describe.
 *
 * - `json`: the JSON a Python value serializes to, as pydantic, FastAPI and `json.dumps` produce it. `datetime` and
 *   `UUID` are strings, sets are arrays, only serialized properties appear.
 * - `runtime`: the closest native JavaScript value: `Date`, `Set`, `Map` for non-string keys, `Uint8Array`.
 */
export type TypeScriptMode = 'json' | 'runtime';

/**
 * How a Python `Enum` is written.
 *
 * - `union`: a union of its values (`'red' | 'green'`). Type-only, so it is valid in a `.d.ts` and under
 *   `erasableSyntaxOnly`.
 * - `enum` / `const-enum`: a TypeScript enum keeping member names.
 * - `object`: an `as const` object plus a type of its values, the erasable pattern that keeps member names.
 */
export type TypeScriptEnumStyle = 'union' | 'enum' | 'const-enum' | 'object';

export interface PythonToTypeScriptOptions extends CommonOptions {
  /** Default: `'json'`. */
  mode?: TypeScriptMode;
  /** Object types as `interface X {}` or `type X = {}`. Default: `'interface'`. */
  objectStyle?: 'interface' | 'type';
  /** Default: `'union'`. */
  enumStyle?: TypeScriptEnumStyle;
  /** Python `int` as `number` or `bigint`. Default: `'number'`. */
  int?: 'number' | 'bigint';
  /** What Python `None` becomes. Default: `'null'`, as JSON has it. */
  none?: 'null' | 'undefined';
  /** Use pydantic aliases (`Field(alias=...)`, `alias_generator`) as property names, as FastAPI responses do. Default: true. */
  useAliases?: boolean;
  /** Fields with a default are `'required'` (always present on instances) or `'optional'` (may be omitted on input). Default: `'required'`. */
  defaultedFields?: 'required' | 'optional';
  /** Default: `'single'`. */
  quote?: QuoteStyle;
  /** Default: true. */
  semicolons?: boolean;
  /** Spaces per indentation level. Default: 2. */
  indent?: number;
  /** Extension for relative imports between generated modules. Default: `'.js'`, which NodeNext and bundlers both resolve. */
  importExtension?: string;
}

export const DEFAULT_TYPESCRIPT_MODE: TypeScriptMode = 'json';
export const DEFAULT_TYPESCRIPT_ENUM_STYLE: TypeScriptEnumStyle = 'union';
export const DEFAULT_IMPORT_EXTENSION = '.js';

// ---------------------------------------------------------------------------
// TypeScript → Python
// ---------------------------------------------------------------------------

/**
 * A Python version the output must run on; 3.11 is the oldest supported. A feature newer than the target is imported
 * from `typing_extensions` (`ReadOnly`, `TypeVar(default=...)`) or written the older way (`TypeVar` instead of PEP 695).
 */
export type PythonVersion = '3.11' | '3.12' | '3.13' | '3.14';

export const PYTHON_VERSIONS: readonly PythonVersion[] = ['3.11', '3.12', '3.13', '3.14'];
export const DEFAULT_PYTHON_VERSION: PythonVersion = '3.12';

/**
 * What a TypeScript interface or object type becomes.
 *
 * - `typeddict`: structural, over plain dicts. The faithful match for JSON-shaped interfaces.
 * - `dataclass`: a `@dataclass`.
 * - `pydantic`: a pydantic v2 `BaseModel`, with validation, aliases and discriminated unions.
 * - `protocol`: a `typing.Protocol`, structural over attributes.
 *
 * Interfaces with methods always become protocols.
 */
export type PythonObjectStyle = 'typeddict' | 'dataclass' | 'pydantic' | 'protocol';

export interface TypeScriptToPythonOptions extends CommonOptions {
  /** Default: {@link DEFAULT_PYTHON_VERSION}. */
  pythonVersion?: PythonVersion;
  /** Default: `'typeddict'`. */
  objectStyle?: PythonObjectStyle;
  /** What a TypeScript `class` becomes. Default: `'pydantic'` when `objectStyle` is `'pydantic'`, else `'dataclass'`. */
  classStyle?: 'dataclass' | 'pydantic';
  /** TypeScript `number` as `float` (PEP 484 accepts an `int` for it), `int`, or `int | float`. Default: `'float'`. */
  number?: 'float' | 'int' | 'int | float';
  /** A TypeScript enum as an `Enum` class or a `Literal[...]` alias. Default: `'enum'`. */
  enumStyle?: 'enum' | 'literal';
  /** Give anonymous object and callable types a name so they can be classes and protocols. Default: true. */
  hoist?: boolean;
  /** Emit `__all__`. Default: only when some declarations are not exported. */
  dunderAll?: boolean;
}

export const DEFAULT_PYTHON_OBJECT_STYLE: PythonObjectStyle = 'typeddict';
